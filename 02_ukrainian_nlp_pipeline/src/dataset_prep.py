def clean_input_text(raw_text: str) -> str:
    """Очищає текст від посилань та зайвих пробілів, зберігаючи кирилицю, латиницю та базову пунктуацію."""
    text_without_links = re.sub(r"http\S+|www\.\S+", " ", raw_text)
    normalized_spaces = re.sub(r"\s+", " ", text_without_links)
    return normalized_spaces.strip()


